export function generateMarkdownReport(checkpointData) {
  const { id, timestamp, period, summary, coaching, previousChanges } = checkpointData;

  const date = new Date(timestamp).toLocaleDateString('ko-KR', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  let md = `# 문제해결 코칭 리포트 - Coach M

**점검일**: ${date}
**분석 기간**: ${period.from} ~ ${period.to}
**분석 대상**: 세션 ${summary.sessionsAnalyzed}개 | 프롬프트 ${summary.promptsAnalyzed}개 | 커밋 ${summary.commitsAnalyzed}개

---

## 이번 기간의 핵심 메시지

> ${coaching.overallNarrative || '분석 결과가 없습니다.'}

`;

  // 점수 테이블
  if (coaching.dimensions?.length > 0) {
    md += `## 종합 점수\n\n`;
    md += `| 영역 | 점수 | 변화 |\n`;
    md += `|------|------|------|\n`;
    for (const dim of coaching.dimensions) {
      const change = previousChanges?.find((c) => c.name === dim.name);
      const changeStr = change
        ? change.change > 0
          ? `+${change.change} ↑`
          : change.change < 0
            ? `${change.change} ↓`
            : '→'
        : 'NEW';
      md += `| ${dim.name} | ${dim.score}/10 | ${changeStr} |\n`;
    }
    md += '\n';
  }

  // 각 차원별 상세
  if (coaching.dimensions) {
    for (const dim of coaching.dimensions) {
      md += `## ${dim.name} (${dim.score}/10)\n\n`;
      md += `${dim.narrative || ''}\n\n`;

      if (dim.cases?.length > 0) {
        const goodCases = dim.cases.filter((c) => c.good);
        const betterCases = dim.cases.filter((c) => c.better);

        if (goodCases.length > 0) {
          md += `### 잘한 사례\n`;
          for (const c of goodCases) {
            md += `- **[${c.sessionRef}]** ${c.what}\n  → ${c.good}\n`;
          }
          md += '\n';
        }

        if (betterCases.length > 0) {
          md += `### 이렇게 하면 더 좋아요\n`;
          for (const c of betterCases) {
            md += `- **[${c.sessionRef}]** ${c.what}\n  → ${c.better}\n`;
          }
          md += '\n';
        }
      }

      if (dim.actionItems?.length > 0) {
        md += `### 실행 조언\n`;
        for (const item of dim.actionItems) {
          md += `- ${item}\n`;
        }
        md += '\n';
      }
    }
  }

  // 성장 분석
  if (coaching.growthFromLast) {
    md += `## 이전 점검 대비 성장\n\n`;
    md += `${coaching.growthFromLast}\n\n`;
  }

  // 강점
  if (coaching.topStrengths?.length > 0) {
    md += `## 강점\n`;
    for (const s of coaching.topStrengths) {
      md += `1. ${s}\n`;
    }
    md += '\n';
  }

  // 개선 영역
  if (coaching.focusAreas?.length > 0) {
    md += `## 집중 개선 영역\n`;
    for (const f of coaching.focusAreas) {
      md += `1. ${f}\n`;
    }
    md += '\n';
  }

  // 프롬프트 예시
  if (coaching.promptExamples) {
    md += `## 프롬프트 개선 예시\n\n`;
    md += `**개선 전:**\n> ${coaching.promptExamples.before}\n\n`;
    md += `**개선 후:**\n> ${coaching.promptExamples.after}\n\n`;
    md += `**이유:** ${coaching.promptExamples.explanation}\n\n`;
  }

  // 다음 목표
  if (coaching.nextGoals?.length > 0) {
    md += `## 다음 점검까지 목표\n`;
    for (const g of coaching.nextGoals) {
      md += `- [ ] ${g}\n`;
    }
    md += '\n';
  }

  md += `---\n*Generated by MetaCognition Coach (Coach M)*\n`;

  return md;
}
